package screen

import "unicode"

// Width returns how many terminal columns r takes: 0 for combining marks and
// other zero-width characters, 2 for East Asian wide and fullwidth characters
// and emoji, and 1 otherwise. Control characters return 0; callers replace
// them before drawing.
func Width(r rune) int {
	switch {
	case isControl(r):
		return 0
	case r < 0x300:
		return 1
	case isZeroWidth(r):
		return 0
	case inRanges(r, wideRanges):
		return 2
	}
	return 1
}

// DrawnWidth is the columns r takes once Grid.Put has drawn it: the same as
// Width, except that a control character is drawn as U+FFFD, one column wide.
func DrawnWidth(r rune) int {
	if isControl(r) {
		return 1
	}
	return Width(r)
}

// StringWidth returns the columns s takes once drawn.
func StringWidth(s string) int {
	n := 0
	for _, r := range s {
		n += DrawnWidth(r)
	}
	return n
}

func isControl(r rune) bool { return r < 0x20 || (r >= 0x7f && r < 0xa0) }

func isZeroWidth(r rune) bool {
	return unicode.In(r, unicode.Mn, unicode.Me) ||
		(r >= 0x1160 && r <= 0x11ff) || // Hangul jungseong and jongseong, which join the preceding syllable
		(r >= 0x200b && r <= 0x200f) || // zero-width space, joiners, direction marks
		(r >= 0x2028 && r <= 0x202e) ||
		(r >= 0x2060 && r <= 0x2064) ||
		(r >= 0xfe00 && r <= 0xfe0f) || // variation selectors
		r == 0xfeff
}

type runeRange struct{ lo, hi rune }

func inRanges(r rune, ranges []runeRange) bool {
	lo, hi := 0, len(ranges)
	for lo < hi {
		mid := (lo + hi) / 2
		switch {
		case r < ranges[mid].lo:
			hi = mid
		case r > ranges[mid].hi:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}

